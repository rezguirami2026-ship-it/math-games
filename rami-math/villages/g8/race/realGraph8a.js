// ١٤-١ الرسوم البيانية الواقعية (١) — «لوحة المراحل»: المدرّب عادل يرسم رحلة عدّاء على رسم المسافة والزمن بثلاث مراحل: يمشي، ثم يتوقف
// (الخط أفقي)، ثم يكمل. قراءة زمن المرحلة الأولى ومسافتها، ومدة التوقف، والزمن والمسافة الكليين، وأي المرحلتين أسرع (الأكثر ميلاً)،
// ونقر نقطة بدء التوقف على الرسم. الإجابة تظهر على الرسم بعد الحل. التحدي: ٨ أسئلة من 8Mt1 (الكتاب ص٩١–٩٢).
import { mission } from '../../mission.js';
import { N, R, eq } from '../../math.js';
import { choice, num, tf } from '../../../missions/challenge.js';
import { trackBg, say, glow, dtGraph, RED } from './art.js';

const who = { name: 'المدرّب عادل', face: '🏃🏽‍♂️', id: 'adel' };
const pick = a => a[Math.floor(Math.random() * a.length)];
// رحلة: يمشي a دقائق مسافة d1 كم، يتوقف s دقائق، يمشي b دقائق مسافة d2 كم (بالعشرات من الدقائق وأنصاف الكيلومترات)
function trip() { let a, s, b, d1, d2; do { a = pick([10, 20]); s = pick([10, 20]); b = pick([10, 20]); d1 = R(2, 6) / 2; d2 = R(1, 6) / 2; } while (eq(d1 / a, d2 / b) || a + s + b > 50 || d1 + d2 > 5); return { a, s, b, d1, d2, pts: [[0, 0], [a, d1], [a + s, d1], [a + s + b, d1 + d2]] }; }
const NAMES = ['هيثم', 'سالم', 'نورة', 'فاطمة'];

function draw(g, w, h, t, S) {
  const r = S.r ? S.r.data : {}; trackBg(g, w, h, t);
  if (r.T) dtGraph(g, w * .16, h * .1, w * .74, h * .66, 50, 5, [{ pts: r.T.pts, col: RED }], { xs: 10, ys: .5, xl: 'الزمن بالدقائق', yl: 'المسافة بالكيلومترات', mark: S.done ? r.mark : null });
  if (S.done && r.ans) say(g, r.ans, w * .5, h * .97, 16, '#15803D', 900);
  glow(g, w, h, S);
}

function make(i) {
  const T = trip(), nm = pick(NAMES), base = { T };
  if (i === 0) return { q: `يبيّن الرسم رحلة ${nm} من البيت إلى المضمار. كم دقيقة استغرق الجزء الأول من الرحلة قبل التوقف؟`, input: { type: 'num' }, sol: T.a, ok: v => v === T.a,
    hint: 'أين يصير الخط أفقياً أول مرة؟ اقرأ الزمن تحت تلك النقطة على المحور الأفقي.', bad: v => v === T.d1 ? 'هذه المسافة: الزمن على المحور الأفقي.' : '',
    good: `${N(T.a)} دقيقة`, data: { ...base, mark: [T.a, T.d1], ans: `المرحلة الأولى ${N(T.a)} دقيقة` } };
  if (i === 1) return { q: `كم كيلومتراً قطع ${nm} في الجزء الأول من الرحلة؟`, input: { type: 'num', dot: true }, sol: T.d1, ok: v => eq(v, T.d1),
    hint: 'اقرأ ارتفاع الخط عند نهاية الجزء الأول على المحور الرأسي.', bad: v => v === T.a ? 'هذا الزمن: المسافة على المحور الرأسي.' : '',
    good: `${N(T.d1)} كم`, data: { ...base, mark: [T.a, T.d1], ans: `${N(T.d1)} كم` } };
  if (i === 2) return { q: `توقّف ${nm} لينتظر الحافلة. كم دقيقة انتظر؟`, input: { type: 'num' }, sol: T.s, ok: v => v === T.s,
    hint: 'الخط الأفقي يعني أنه لا يتحرك: من أي زمن إلى أي زمن؟', bad: v => v === T.a + T.s ? 'هذا زمن نهاية التوقف من البداية: اطرح زمن بدايته.' : '',
    good: `من ${N(T.a)} إلى ${N(T.a + T.s)}: ${N(T.s)} دقيقة`, data: { ...base, mark: [T.a + T.s, T.d1], ans: `انتظر ${N(T.s)} دقيقة` } };
  if (i === 3) { const k = R(0, 1), v0 = k ? T.d1 + T.d2 : T.a + T.s + T.b;
    return { q: `ما ${k ? 'المسافة الكلية بالكيلومترات' : 'الزمن الكلي للرحلة بالدقائق'}؟`, input: { type: 'num', dot: true }, sol: v0, ok: v => eq(v, v0),
      hint: 'اقرأ آخر نقطة على الرسم.', bad: () => '', good: `${N(v0)}`, data: { ...base, mark: [T.a + T.s + T.b, T.d1 + T.d2], ans: `${k ? 'المسافة' : 'الزمن'} ${N(v0)}` } }; }
  if (i === 4) { const fast = T.d1 / T.a > T.d2 / T.b ? 0 : 1;
    return { q: `في أي المرحلتين كان ${nm} أسرع؟`, input: { type: 'pick', opts: ['المرحلة الأولى', 'المرحلة الأخيرة'] }, ok: v => v === fast,
      hint: 'أي الجزأين أكثر ميلاً؟ الميل الأكبر يعني مسافة أكبر في الزمن نفسه.', bad: () => 'قارن الميل: المسافة ÷ الزمن لكل مرحلة.',
      good: `${N(T.d1)} كم في ${N(T.a)} دقيقة و${N(T.d2)} كم في ${N(T.b)} دقيقة`, data: { ...base, ans: `الأسرع: ${['الأولى', 'الأخيرة'][fast]}` } }; }
  return { q: 'انقر النقطة على الرسم التي بدأ عندها التوقف.', input: { type: 'grid', x0: 0, x1: 5, y0: 0, y1: 10, n: 1, segs: [[[0, 0], [T.a / 10, T.d1 * 2]], [[T.a / 10, T.d1 * 2], [(T.a + T.s) / 10, T.d1 * 2]], [[(T.a + T.s) / 10, T.d1 * 2], [(T.a + T.s + T.b) / 10, (T.d1 + T.d2) * 2]]] }, sol: [[T.a / 10, T.d1 * 2]], ok: v => v[0][0] === T.a / 10 && v[0][1] === T.d1 * 2,
    hint: 'التوقف يبدأ حيث يصير الخط أفقياً.', bad: v => v[0][0] === (T.a + T.s) / 10 ? 'هذه نهاية التوقف.' : 'ابحث عن أول نقطة يصير بعدها الخط أفقياً.',
    good: `بدأ التوقف بعد ${N(T.a)} دقيقة`, data: { ...base, mark: [T.a, T.d1], ans: 'بداية التوقف' } };
}

function challenge() {
  const items = [];
  items.push(choice('في رسم المسافة والزمن، الجزء الأفقي يعني أن الشخص:', 'متوقف', ['يسرع', 'يعود إلى البداية', 'يمشي ببطء'], 'المسافة لا تتغير.', '8Mt1'));
  items.push(choice('الجزء الأكثر ميلاً في رسم المسافة والزمن يعني:', 'أسرع حركة', ['أبطأ حركة', 'التوقف', 'العودة'], 'مسافة أكبر في زمن أقل.', '8Mt1'));
  items.push(tf('إذا انحدر الخط إلى الأسفل في رسم المسافة من البيت، فالشخص يعود نحو البيت.', true, 'المسافة من البداية تقل.', '8Mt1', 'الميل السالب = اقتراب من البداية.'));
  items.push(num('مشى هيثم ١ كم في ١٠ دقائق، ثم انتظر ٢٠ دقيقة، ثم مشى ٠٫٥ كم في ١٠ دقائق. ما الزمن الكلي بالدقائق؟', 40, 'اجمع أزمنة المراحل.', '8Mt1'));
  items.push(num('مشى هيثم ١ كم ثم انتظر ثم مشى ٠٫٥ كم. ما المسافة الكلية بالكيلومترات؟', 1.5, 'اجمع المسافات.', '8Mt1', { dot: true }));
  items.push(tf('الخط الأفقي في رسم المسافة والزمن يعني أن السرعة كبيرة.', false, 'هل تتغير المسافة؟', '8Mt1', 'السرعة صفر.'));
  items.push(num('سيارة قطعت ١٥٠ كم في ساعتين ثم توقفت نصف ساعة. كم ساعة مضت حتى نهاية التوقف؟', 2.5, 'اجمع.', '8Mt1', { dot: true }));
  items.push(choice('في رسم المسافة والزمن يوضع الزمن عادة على:', 'المحور الأفقي', ['المحور الرأسي', 'المحورين معاً', 'لا يوضع'], 'المتغير المستقل.', '8Mt1'));
  return items.sort(() => Math.random() - .5);
}

export default mission({
  title: 'لوحة المراحل', icon: '📈', who, rounds: 6, make, draw,
  intro: ['أهلاً بك في مضمار السباق! أنا عادل، أدرّب العدّائين.', 'أرسم كل رحلة على رسم المسافة والزمن: الخط الصاعد حركة، والأفقي توقف. اقرأ الرسم معي.'],
  outro: ['ممتاز! صرت تقرأ الرحلة من خطها.', 'تحدي الرسوم البيانية الواقعية.'],
  challenge: { title: 'تحدي قراءة الرسم', make: challenge }
});
export const ROUNDS = 6;
export { make, challenge };
