// ١٤-٤ حل مسائل متوسط السرعة — «لوحة التوقيت»: الميقاتي عمر يحسب متوسط السرعة = المسافة الكلية ÷ الزمن الكلي، ومثلث ف ع ن:
// السرعة من مسافة وزمن بكسر من الساعة (٣ ساعات وربع = ٣٫٢٥)، والزمن من مسافة وسرعة (بالدقائق والثواني)، والمسافة من سرعة وزمن،
// ومتوسط السرعة لرحلة بمرحلتين. القيمة المطلوبة «؟» حتى يحلّ الطالب. التحدي: ٨ أسئلة من 8Mt2 (الكتاب ص٩٨–٩٩).
import { mission } from '../../mission.js';
import { N, R, eq, fr } from '../../math.js';
import { choice, num, tf } from '../../../missions/challenge.js';
import { trackBg, say, glow, sdt } from './art.js';

const who = { name: 'الميقاتي عمر', face: '⏱️', id: 'omar8' };
const pick = a => a[Math.floor(Math.random() * a.length)];
const r1 = v => Math.round(v * 10) / 10;
const QUART = [[.25, 'ربع'], [.5, 'نصف'], [.75, 'ثلاثة أرباع']];
const hrs = H => H === 1 ? 'ساعة' : H === 2 ? 'ساعتين' : `${N(H)} ساعات`;

function draw(g, w, h, t, S) {
  const r = S.r ? S.r.data : {}; trackBg(g, w, h, t);
  g.fillStyle = 'rgba(255,255,255,.95)'; g.beginPath(); g.roundRect(w * .06, h * .36, w * .88, h * .52, 16); g.fill();
  sdt(g, w * .2, h * .6, Math.min(70, h * .16), r.hl || '');
  (r.lines || []).forEach((l, k) => say(g, l, w * .62, h * .5 + k * 28, 17, '#334155', 800));
  say(g, S.done ? r.ans : r.ask || '', w * .62, h * .84, 18, S.done ? '#15803D' : '#7C2D12', 900);
  glow(g, w, h, S);
}

function make(i) {
  if (i === 0) { const v = R(6, 12) * 10, H = R(1, 4), q = pick(QUART), T = H + q[0], D = Math.round(v * T), ans = r1(D / T);
    return { q: `قطع قطار الصحراء ${N(D)} كم في ${hrs(H)} و${q[1]} ساعة. ما متوسط سرعته بالكيلومتر في الساعة؟`, input: { type: 'num', dot: true, calc: true }, sol: ans, ok: x => eq(x, ans),
      hint: 'اكتب الزمن كسراً عشرياً من الساعات أولاً، ثم السرعة = المسافة ÷ الزمن.', bad: x => eq(x, r1(D / H)) ? 'لا تنسَ جزء الساعة.' : q[0] === .25 && eq(x, r1(D / (H + .15))) ? 'ربع الساعة = ٠٫٢٥ لا ٠٫١٥.' : '',
      good: `${N(D)} ÷ ${N(T)} ≈ ${N(ans)} كم/س`, data: { hl: 'ع', lines: [`المسافة ${N(D)} كم`, `الزمن ${N(T)} ساعة`], ask: 'السرعة = ؟', ans: `${N(ans)} كم/س` } }; }
  if (i === 1) { let d, v; do { d = pick([800, 1200, 600, 1000, 1500]); v = pick([6, 8, 5, 4]); } while (d % v); const s = d / v, mm = Math.floor(s / 60), ss = Math.round(s % 60);
    return { q: `ركض أحمد ${N(d)} م بمتوسط سرعة ${N(v)} أمتار في الثانية. كم استغرق؟ اكتب الدقائق ثم الثواني.`, input: { type: 'blanks', tpl: '{} دقيقة و{} ثانية' }, sol: [mm, ss], ok: x => x[0] === mm && x[1] === ss,
      hint: 'الزمن = المسافة ÷ السرعة بالثواني، ثم حوّل الثواني إلى دقائق وثوانٍ.', bad: x => x[0] === Math.floor(s) ? 'هذا عدد الثواني كله: حوّله إلى دقائق.' : '',
      good: `${N(d)} ÷ ${N(v)} = ${N(r1(s))} ثانية = ${N(mm)} دقيقة و${N(ss)} ثانية`, data: { hl: 'ن', lines: [`المسافة ${N(d)} م`, `السرعة ${N(v)} م/ث`], ask: 'الزمن = ؟', ans: `${N(mm)} دقيقة و${N(ss)} ثانية` } }; }
  if (i === 2) { const v = R(4, 12) * 10, q = pick(QUART), H = R(1, 3), T = H + q[0], D = r1(v * T);
    return { q: `تسير سيارة الإسعاف بمتوسط سرعة ${N(v)} كم/س لمدة ${hrs(H)} و${q[1]} ساعة. كم كيلومتراً تقطع؟`, input: { type: 'num', dot: true }, sol: D, ok: x => eq(x, D),
      hint: 'المسافة = السرعة × الزمن، والزمن بالساعات كسراً عشرياً.', bad: x => eq(x, v * H) ? 'لا تنسَ جزء الساعة.' : '',
      good: `${N(v)} × ${N(T)} = ${N(D)} كم`, data: { hl: 'ف', lines: [`السرعة ${N(v)} كم/س`, `الزمن ${N(T)} ساعة`], ask: 'المسافة = ؟', ans: `${N(D)} كم` } }; }
  if (i === 3) { let d1, t1, d2, t2; do { d1 = R(4, 12) * 10; t1 = pick([1, 2]); d2 = R(4, 12) * 10; t2 = pick([1, 2, 3]); } while (!Number.isInteger((d1 + d2) / (t1 + t2)) || d1 / t1 === d2 / t2);
    const v = (d1 + d2) / (t1 + t2);
    return { q: `قطع درّاج ${N(d1)} كم في ${t1 === 1 ? 'ساعة' : 'ساعتين'}، ثم ${N(d2)} كم في ${t2 === 1 ? 'ساعة' : t2 === 2 ? 'ساعتين' : `${N(t2)} ساعات`}. ما متوسط سرعته للرحلة كلها؟`, input: { type: 'num', dot: true }, sol: v, ok: x => eq(x, v),
      hint: 'متوسط السرعة = المسافة الكلية ÷ الزمن الكلي، لا متوسط السرعتين.', bad: x => eq(x, (d1 / t1 + d2 / t2) / 2) ? 'هذا متوسط السرعتين: احسب من المجموعين.' : '',
      good: `${N(d1 + d2)} ÷ ${N(t1 + t2)} = ${N(v)} كم/س`, data: { hl: 'ع', lines: [`المسافة ${N(d1 + d2)} كم`, `الزمن ${N(t1 + t2)} ساعة`], ask: 'متوسط السرعة = ؟', ans: `${N(v)} كم/س` } }; }
  if (i === 4) { const v = pick([60, 80, 90, 120]), d = v * pick([1.5, 2.5, .75, 1.25]), T = d / v, mins = Math.round(T * 60);
    return { q: `تسير حافلة السباق بمتوسط سرعة ${N(v)} كم/س. كم دقيقة تحتاج لقطع ${N(d)} كم؟`, input: { type: 'num' }, sol: mins, ok: x => x === mins,
      hint: 'الزمن بالساعات = المسافة ÷ السرعة. ثم كم دقيقة في الساعة؟', bad: x => eq(x, T) ? 'هذا بالساعات: حوّل إلى دقائق.' : '',
      good: `${N(d)} ÷ ${N(v)} = ${N(T)} ساعة = ${N(mins)} دقيقة`, data: { hl: 'ن', lines: [`المسافة ${N(d)} كم`, `السرعة ${N(v)} كم/س`], ask: 'الزمن = ؟', ans: `${N(mins)} دقيقة` } }; }
  const opts = ['المسافة ÷ الزمن', 'الزمن ÷ المسافة', 'المسافة × الزمن', 'المسافة − الزمن'], sh = opts.map(v => [Math.random(), v]).sort((a, b) => a[0] - b[0]).map(x => x[1]);
  return { q: 'غطِّ حرف ع في مثلث ف ع ن. ماذا يبقى لحساب السرعة؟', input: { type: 'pick', opts: sh }, ok: x => sh[x] === opts[0],
    hint: 'ف فوق الخط وع × ن تحته: إذا غطّيت ع يبقى ف فوق ن.', bad: () => 'الخط الأفقي في المثلث يعني القسمة.', good: 'ع = ف ÷ ن', data: { hl: 'ع', lines: ['ف = ع × ن'], ask: 'ع = ؟', ans: 'ع = ف ÷ ن' } };
}

function challenge() {
  const items = [];
  items.push(num('استغرق عمر ٣ ساعات وربع لقطع ٢٧٣ كم. ما متوسط سرعته بالكيلومتر في الساعة؟', 84, '٢٧٣ ÷ ٣٫٢٥.', '8Mt2'));
  items.push(choice('٣ ساعات وربع بالكسر العشري:', '٣٫٢٥', ['٣٫١٥', '٣٫٤', '٣٫٢'], 'الربع = ٠٫٢٥.', '8Mt2'));
  items.push(num('ركض ٨٠٠ م بسرعة ٦ م/ث. كم ثانية استغرق لأقرب عدد كامل؟', 133, '٨٠٠ ÷ ٦.', '8Mt2'));
  items.push(num('سيارة سرعتها ٩٠ كم/س لمدة ساعتين ونصف. كم كيلومتراً قطعت؟', 225, '٩٠ × ٢٫٥.', '8Mt2'));
  items.push(tf('متوسط السرعة لرحلتين = متوسط السرعتين دائماً.', false, 'جرّب زمنين مختلفين.', '8Mt2', 'المسافة الكلية ÷ الزمن الكلي.'));
  items.push(choice('وحدة السرعة حين تُقاس المسافة بالأمتار والزمن بالثواني:', 'م/ث', ['كم/س', 'م/س', 'كم/ث'], 'مسافة لكل زمن.', '8Mt2'));
  items.push(tf('٤٥ دقيقة = ٠٫٧٥ ساعة.', true, '٤٥ ÷ ٦٠.', '8Mt2', 'ثلاثة أرباع الساعة.'));
  items.push(num('قطع ١٢٠ كم في ساعة و١٠٠ كم في ساعتين. ما متوسط السرعة للرحلة كلها لأقرب عدد كامل؟', 73, '٢٢٠ ÷ ٣.', '8Mt2'));
  return items.sort(() => Math.random() - .5);
}

export default mission({
  title: 'لوحة التوقيت', icon: '⏱️', who, rounds: 6, make, draw,
  intro: ['أنا عمر، ميقاتي المضمار. ساعتي لا تخطئ ثانية!', 'مثلث ف ع ن يحفظ لي الصيغ الثلاث: غطِّ ما تريد، ويبقى طريقة حسابه.'],
  outro: ['ممتاز! السرعات والأزمنة كلها مسجلة.', 'تحدي متوسط السرعة.'],
  challenge: { title: 'تحدي السرعة', make: challenge }
});
export const ROUNDS = 6;
export { make, challenge };
