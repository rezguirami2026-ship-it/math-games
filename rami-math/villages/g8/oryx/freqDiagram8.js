// ١٥-٢ تفسير المخططات التكرارية ورسمها — «لوحة الزوار»: المرشد فيصل يعرض المخططات التكرارية: أعمدة متلاصقة للبيانات المتصلة (الأوزان)،
// وأعمدة منفصلة للبيانات المنفصلة (عدد المها في كل قطيع). قراءة تكرار فئة، والفرق بين فئتين، والمجموع، ورسم المخطط بنفسه: يرفع الطالب كل عمود
// إلى تكراره بزرّي + و−. التحدي: ٨ أسئلة من 8Dc1 (الكتاب ص١١١–١١٢).
import { mission } from '../../mission.js';
import { N, R } from '../../math.js';
import { choice, num, tf } from '../../../missions/challenge.js';
import { plainBg, say, glow, axes, bars, cls, OLIVE } from './art.js';

const who = { name: 'المرشد فيصل', face: '🧑🏽‍🏫', id: 'faisal' };
const pick = a => a[Math.floor(Math.random() * a.length)];
const CL = [[60, 70], [70, 80], [80, 90], [90, 100]], LAB = CL.map(([a, b]) => `${N(a)}–${N(b)}`);
const GR = ['١–٣', '٤–٧', '٨–١١', '١٢–١٥'];

function draw(g, w, h, t, S) {
  const r = S.r ? S.r.data : {}; plainBg(g, w, h, t);
  const A = axes(g, w * .14, h * .44, w * .78, h * .44, r.M || 10, r.labels || LAB, { title: r.title || '' });
  const fr = r.draw ? (S.done ? r.fr : (S.v || r.fr.map(() => 0))) : r.fr;
  bars(g, A, fr, { gap: r.discrete ? A.bw * .18 : 0, hide: S.done ? -1 : r.hide ?? -1 });
  glow(g, w, h, S);
}

function make(i) {
  const fr = CL.map(() => R(2, 9));
  if (i === 0) { const k = R(0, 3);
    return { q: `يبيّن المخطط أوزان المها في المحمية بالكيلوغرام. كم مهاة وزنها في الفئة ${cls(...CL[k])}؟`, input: { type: 'num' }, sol: fr[k], ok: v => v === fr[k],
      hint: 'ابحث عن عمود الفئة، ثم اقرأ ارتفاعه على محور التكرار.', bad: v => v === CL[k][1] ? 'هذا حدّ الفئة: اقرأ التكرار على المحور الرأسي.' : '',
      good: `${N(fr[k])} مها`, data: { fr, title: 'أوزان المها بالكيلوغرام' } }; }
  if (i === 1) { let a, b; while (new Set(fr).size < 2) fr.splice(0, 4, ...CL.map(() => R(2, 9))); do { a = R(0, 3); b = R(0, 3); } while (a === b || fr[a] === fr[b]); const [hi, lo] = fr[a] > fr[b] ? [a, b] : [b, a];
    return { q: `بكم يزيد عدد المها في الفئة ${cls(...CL[hi])} على عددها في الفئة ${cls(...CL[lo])}؟`, input: { type: 'num' }, sol: fr[hi] - fr[lo], ok: v => v === fr[hi] - fr[lo],
      hint: 'اقرأ ارتفاع العمودين ثم اطرح.', bad: v => v === fr[hi] + fr[lo] ? 'المطلوب الفرق لا المجموع.' : '', good: `${N(fr[hi])} − ${N(fr[lo])} = ${N(fr[hi] - fr[lo])}`, data: { fr, title: 'أوزان المها بالكيلوغرام' } }; }
  if (i === 2) { const tot = fr.reduce((a, b) => a + b, 0);
    return { q: 'كم مهاة وُزنت كلها في هذا المخطط؟', input: { type: 'num' }, sol: tot, ok: v => v === tot, hint: 'اجمع ارتفاعات الأعمدة كلها.', bad: () => '', good: `${fr.map(N).join(' + ')} = ${N(tot)}`, data: { fr, title: 'أوزان المها بالكيلوغرام' } }; }
  if (i === 3 || i === 4) { const f2 = CL.map(() => R(1, 9)), discrete = i === 4, labels = discrete ? GR : LAB;
    return { q: discrete ? `ارسم المخطط التكراري لعدد المها في القطعان: التكرارات ${f2.map(N).join(' و')} للفئات ${GR.join(' و')}، بأعمدة منفصلة.` : `ارسم المخطط التكراري لأوزان المها: التكرارات ${f2.map(N).join(' و')} للفئات الأربع من اليسار إلى اليمين.`,
      input: { type: 'mix', parts: labels.map(l => ({ name: l, col: '#4D7C0F' })), min: 0, max: 10, label: '✓ ثبّت المخطط' }, sol: f2, ok: v => v.every((x, k) => x === f2[k]),
      hint: 'كل عمود يرتفع إلى تكرار فئته على المحور الرأسي.', bad: v => v.some((x, k) => x === f2[3 - k] && x !== f2[k]) ? 'رتّب الأعمدة: الفئة الأولى أولاً كما في الجدول.' : 'تحقق من ارتفاع كل عمود.',
      good: 'المخطط مطابق للجدول', data: { fr: f2, draw: 1, discrete, labels, title: discrete ? 'عدد المها في القطيع' : 'أوزان المها بالكيلوغرام' } }; }
  return { q: 'أي البيانات تُرسم بأعمدة متلاصقة بلا فراغات بينها؟', input: { type: 'pick', opts: ['البيانات المتصلة مثل الأوزان', 'البيانات المنفصلة مثل عدد المها', 'الألوان'] }, ok: v => v === 0,
    hint: 'هل يمكن أن تأخذ الكتلة أي قيمة بين ٦٠ و٧٠؟ وهل يمكن أن يكون عدد المها ٤٫٥؟', bad: () => 'البيانات المنفصلة قيم محددة، فبين أعمدتها مسافات.', good: 'المتصلة: أعمدة متلاصقة', data: { fr, title: 'أعمدة متلاصقة' } };
}

function challenge() {
  const items = [];
  items.push(choice('في المخطط التكراري للبيانات المتصلة:', 'لا توجد مسافات بين الأعمدة', ['توجد مسافات متساوية', 'الأعمدة بألوان مختلفة', 'الأعمدة أفقية'], 'القيم متصلة.', '8Dc1'));
  items.push(choice('أي البيانات منفصلة؟', 'عدد الأطفال في الأسرة', ['أطوال الطلاب', 'كتل الحقائب', 'درجات الحرارة'], 'قيم محددة فقط.', '8Dc1'));
  items.push(num('أعمدة مخطط: ٦ و٥ و٩ و٤. كم القيم كلها؟', 24, 'اجمع.', '8Dc1'));
  items.push(num('عمود فئة ٨–١١ ارتفاعه ٩ وعمود ١٢–١٥ ارتفاعه ٤. ما الفرق؟', 5, 'اطرح.', '8Dc1'));
  items.push(tf('يُكتب اسم مجموعة البيانات أسفل كل عمود في مخطط البيانات المنفصلة.', true, 'كيف تعرف الفئة؟', '8Dc1', 'تسمية واضحة لكل عمود.'));
  items.push(tf('ارتفاع العمود في المخطط التكراري يمثل حدّ الفئة.', false, 'ماذا يقيس المحور الرأسي؟', '8Dc1', 'يمثل التكرار.'));
  items.push(choice('أعلى عمود في المخطط التكراري يدل على:', 'الفئة الأكثر تكراراً', ['الفئة الأكبر قيمة', 'المدى', 'الوسيط'], 'الأعلى = الأكثر.', '8Dc1'));
  items.push(num('مخطط: ٣ و٨ و٦ و٣ في أربع فئات. كم قيمة في الفئتين الأوليين معاً؟', 11, '٣ + ٨.', '8Dc1'));
  return items.sort(() => Math.random() - .5);
}

export default mission({
  title: 'لوحة الزوار', icon: '📊', who, rounds: 6, make, draw,
  intro: ['أنا فيصل، مرشد الزوار في المحمية. أعرض لهم بيانات المها بمخططات.', 'العمود يرتفع بقدر التكرار: الأوزان أعمدتها متلاصقة، وأعداد القطعان أعمدتها منفصلة.'],
  outro: ['رائع! صار الزوار يفهمون المخططات.', 'تحدي المخططات التكرارية.'],
  challenge: { title: 'تحدي المخططات', make: challenge }
});
export const ROUNDS = 6;
export { make, challenge };
