// ١٥-٣ تفسير المضلعات التكرارية ورسمها — «مشتل الغاف»: المزارع راشد يزرع شتلات الغاف في المشتل وخارجه. المضلع التكراري يصل نقاط المنتصف:
// نقطة منتصف الفئة = (بدايتها + نهايتها) ÷ ٢، ونقطة كل فئة على ارتفاع تكرارها، وأي الفئات أكثر تكراراً من المضلع، والمقارنة بين مضلعين (أيهما أطول
// شتلات). التحدي: ٨ أسئلة من 8Dc1 (الكتاب ص١١٤–١١٥).
import { mission } from '../../mission.js';
import { N, R, eq } from '../../math.js';
import { choice, num, tf } from '../../../missions/challenge.js';
import { plainBg, say, glow, axes, polyline, cls } from './art.js';

const who = { name: 'المزارع راشد', face: '👨🏽‍🌾', id: 'rashid8' };
const pick = a => a[Math.floor(Math.random() * a.length)];
const CL = [[0, 10], [10, 20], [20, 30], [30, 40]], MID = CL.map(([a, b]) => (a + b) / 2), LAB = MID.map(N);

function draw(g, w, h, t, S) {
  const r = S.r ? S.r.data : {}; plainBg(g, w, h, t);
  const A = axes(g, w * .14, h * .44, w * .78, h * .44, 10, LAB, { title: r.title || 'ارتفاع الشتلات (سم) — نقاط المنتصف' });
  (r.polys || []).forEach(([f, col], k) => { if (!r.after || S.done || k === 0) polyline(g, A, f, col); });
  glow(g, w, h, S);
}

function make(i) {
  const f1 = CL.map(() => R(1, 9));
  if (i === 0) { const [a, b] = pick([[10, 20], [20, 30], [60, 70], [15, 25], [150, 160], [0, 10]]), m = (a + b) / 2;
    return { q: `ما نقطة منتصف الفئة ${cls(a, b, 'ع')}؟`, input: { type: 'num', dot: true }, sol: m, ok: v => eq(v, m),
      hint: 'اجمع بداية الفئة ونهايتها ثم اقسم على ٢.', bad: v => eq(v, b - a) ? 'هذا مدى الفئة لا منتصفها.' : eq(v, a + b) ? 'لا تنسَ القسمة على ٢.' : '',
      good: `(${N(a)} + ${N(b)}) ÷ ٢ = ${N(m)}`, data: { polys: [[f1, '#DC2626']] } }; }
  if (i === 1) { const k = R(0, 3);
    return { q: `في المضلع التكراري لارتفاع الشتلات داخل البيت الزراعي، ما تكرار الفئة التي منتصفها ${N(MID[k])} سم؟`, input: { type: 'num' }, sol: f1[k], ok: v => v === f1[k],
      hint: 'ابحث عن النقطة فوق نقطة المنتصف، واقرأ ارتفاعها.', bad: v => v === MID[k] ? 'هذه نقطة المنتصف نفسها: التكرار على المحور الرأسي.' : '', good: `${N(f1[k])}`, data: { polys: [[f1, '#DC2626']] } }; }
  if (i === 2) { let f; do f = CL.map(() => R(1, 9)); while (f.filter(x => x === Math.max(...f)).length > 1); const k = f.indexOf(Math.max(...f));
    return { q: 'أي فئة ارتفاع لها أكبر تكرار في المضلع؟', input: { type: 'pick', opts: CL.map(([a, b]) => cls(a, b, 'ع')) }, ok: v => v === k,
      hint: 'أعلى نقطة في المضلع فوق منتصف أي فئة؟', bad: () => 'ابحث عن أعلى نقطة.', good: cls(...CL[k], 'ع'), data: { polys: [[f, '#DC2626']] } }; }
  if (i === 3) { const k = R(0, 3), tot = f1.reduce((a, b) => a + b, 0);
    return { q: 'كم شتلة قيس ارتفاعها في المضلع كله؟', input: { type: 'num' }, sol: tot, ok: v => v === tot, hint: 'اجمع تكرارات النقاط كلها.', bad: () => '', good: `${f1.map(N).join(' + ')} = ${N(tot)}`, data: { polys: [[f1, '#DC2626']] } }; }
  let fa, fb; do { fa = [R(4, 9), R(3, 8), R(1, 5), R(0, 3)]; fb = [R(0, 3), R(2, 6), R(3, 8), R(4, 9)]; } while (fa.reduce((a, b) => a + b, 0) !== fb.reduce((a, b) => a + b, 0));
  if (i === 4) return { q: 'المضلع الأحمر لشتلات البيت الزراعي، والأزرق للشتلات خارجه، وعددهما متساوٍ. أي المجموعتين شتلاتها أطول؟', input: { type: 'pick', opts: ['داخل البيت الزراعي', 'خارج البيت الزراعي'] }, ok: v => v === 1,
    hint: 'أين تتجمع معظم نقاط كل مضلع: عند الارتفاعات الصغيرة أم الكبيرة؟', bad: () => 'المضلع المرتفع نحو اليمين يعني تكرارات أكبر عند الارتفاعات الأكبر.', good: 'الأزرق مرتفع عند الارتفاعات الكبيرة', data: { polys: [[fa, '#DC2626'], [fb, '#2563EB']], after: 0 } };
  return { q: 'لرسم المضلع التكراري، أين تُرسم نقطة كل فئة على المحور الأفقي؟', input: { type: 'pick', opts: ['عند منتصف الفئة', 'عند بداية الفئة', 'عند نهاية الفئة'] }, ok: v => v === 0,
    hint: 'المضلع يمثل الفئة كلها بنقطة واحدة: أي نقطة تمثلها أفضل؟', bad: () => 'نستعمل نقطة المنتصف لتمثيل الفئة كلها.', good: 'عند نقطة المنتصف', data: { polys: [[f1, '#DC2626']] } };
}

function challenge() {
  const items = [];
  items.push(num('ما نقطة منتصف الفئة ١٠ ≤ ع < ٢٠؟', 15, '(١٠ + ٢٠) ÷ ٢.', '8Dc1'));
  items.push(num('ما نقطة منتصف الفئة ٢٠ ≤ ع < ٣٠؟', 25, '(٢٠ + ٣٠) ÷ ٢.', '8Dc1'));
  items.push(choice('المضلع التكراري يصل بين:', 'نقاط منتصف الفئات على ارتفاع تكراراتها', ['بدايات الفئات', 'نهايات الفئات', 'قمم الأعمدة من طرفها'], 'نقطة واحدة لكل فئة.', '8Dc1'));
  items.push(tf('المضلع التكراري مفيد لعرض الأنماط والاتجاهات في البيانات.', true, 'خطوط تصل النقاط.', '8Dc1', 'ويسهّل مقارنة مجموعتين.'));
  items.push(tf('نقطة منتصف الفئة ٠ ≤ ع < ١٠ هي ١٠.', false, 'اجمع واقسم.', '8Dc1', 'المنتصف ٥.'));
  items.push(choice('لمقارنة توزيعين على رسم واحد نستعمل غالباً:', 'مضلعين تكراريين', ['مخططين متداخلين بالأعمدة', 'جدولاً واحداً', 'دائرة'], 'الخطوط لا تحجب بعضها.', '8Dc1'));
  items.push(num('تكرارات المضلع: ٢ و٤ و٨ و٦. كم القيم كلها؟', 20, 'اجمع.', '8Dc1'));
  items.push(num('ما نقطة منتصف الفئة ١٥٠ < ط ≤ ١٦٠؟', 155, 'اجمع واقسم على ٢.', '8Dc1'));
  return items.sort(() => Math.random() - .5);
}

export default mission({
  title: 'مشتل الغاف', icon: '🌱', who, rounds: 6, make, draw,
  intro: ['أنا راشد، أزرع شتلات الغاف لتظلل المها. أقيس أطوالها وأرسمها مضلعاً تكرارياً.', 'نقطة لكل فئة عند منتصفها، ثم أصل النقاط… فيظهر شكل البيانات وأقارن المشتل بالخارج!'],
  outro: ['أحسنت! المضلعات تحكي قصة الشتلات.', 'تحدي المضلعات التكرارية.'],
  challenge: { title: 'تحدي المضلعات', make: challenge }
});
export const ROUNDS = 6;
export { make, challenge };
