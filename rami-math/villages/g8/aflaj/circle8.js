// ٦-٢ حل مسائل الدائرة — «الجابية»: المزارعة منى تبني جابية دائرية (حوض ماء) وتحيط البيدر بحجارة وتغطي الطوي.
// الطالب يستعمل الآلة الحاسبة بزر π كما في الكتاب ويقرّب إلى منزلة عشرية واحدة: المساحة والمحيط من نصف القطر أو القطر،
// ونصف الدائرة (المساحة، والمحيط مع القطر)، والقطر من المحيط، ونصف القطر من المساحة. التحدي: ٨ أسئلة من 8Ma3 (ص١٠٥–١٠٧).
import { mission } from '../../mission.js';
import { N, R, R1, eq } from '../../math.js';
import { choice, tf } from '../../../missions/challenge.js';
import { farmBg, say, circleFig, glow } from './art.js';

const who = { name: 'المزارعة منى', face: '👩🏽‍🌾', id: 'muna' };
const r1 = x => Math.round(x * 10) / 10, pick = a => a[Math.floor(Math.random() * a.length)];
const PI_HINT = 'يبدو أنك استعملت ٣٫١٤: استعمل زر π في الآلة الحاسبة فهو أدق.';
const NOTE = '(استعمل زر π في الآلة الحاسبة، وقرّب الجواب إلى منزلة عشرية واحدة)';

/* جولة من صيغة f(π): الجواب مقرّب بزر π، ومن قرّب بـ ٣٫١٤ يُنبَّه، وأخطاء بعينها لها ردود */
function round(q, f, hint, errs, data, unit) {
  const ans = r1(f(Math.PI)), alt = r1(f(3.14));
  return { q: `${q}<br><small>${NOTE}</small>`, input: { type: 'num', dot: true, calc: true }, sol: ans, ok: v => eq(v, ans), hint,
    bad: v => { const e = errs.find(([g]) => eq(v, r1(g(Math.PI)))); return e ? e[1] : eq(v, alt) ? PI_HINT : eq(v, Math.round(f(Math.PI))) || eq(v, Math.round(f(Math.PI) * 100) / 100) ? 'قرّب إلى منزلة عشرية واحدة.' : ''; },
    good: `أحسنت! ${N(ans)} ${unit}.`, data: { ...data, ans: `${N(ans)} ${unit}` } };
}

function draw(g, w, h, t, S) {
  const r = S.r ? S.r.data : {}; farmBg(g, w, h, t);
  const cx = w * .27, cy = h * (r.half ? .62 : .52), rad = Math.min(w * .2, h * .36);
  g.fillStyle = 'rgba(0,0,0,.08)'; g.beginPath(); g.ellipse(cx + 8, cy + rad * .95, rad * 1.05, rad * .2, 0, 0, 7); g.fill();
  circleFig(g, cx, cy, rad, { lab: r.lab, diam: r.diam, half: r.half, t, fill: r.fill || (S.done ? 'rgba(59,130,196,.55)' : 'rgba(59,130,196,.3)') });
  say(g, r.title || '', w * .7, h * .16, 20, '#0F766E');
  (r.lines || []).forEach((l, k) => say(g, l, w * .7, h * .32 + k * 28, 17));
  if (S.done && r.ans) say(g, r.ans, w * .7, h * .32 + (r.lines || []).length * 28 + 10, 21, '#15803D');
  glow(g, w, h, S);
}

function make(i) {
  if (i === 0) { const rr = pick([R(3, 12), R1(2, 9.5)]);
    return round(`الجابية حوض دائري نصف قطره ${N(rr)} م. ما مساحة سطح الماء فيها؟`, p => p * rr * rr, 'أي صيغة للمساحة؟ وهل فيها نصف القطر أم القطر؟ ثم ربّعه قبل الضرب في π.',
      [[p => 2 * p * rr, 'هذا المحيط لا المساحة.'], [p => p * 4 * rr * rr, 'عوّضت بالقطر؛ المساحة تحتاج نصف القطر.'], [p => p * rr, 'ربّع نصف القطر أولاً.']],
      { title: 'مساحة الجابية', lab: `${N(rr)} م`, lines: [`نصف القطر = ${N(rr)} م`, 'المساحة = ؟ م²'] }, 'م²'); }
  if (i === 1) { const d = R(6, 20);
    return round(`البيدر دائري قطره ${N(d)} م، تحيطه منى بحجارة. كم متراً طول الحافة (المحيط)؟`, p => p * d, 'المحيط مرتبط بالقطر مباشرة: ما الذي نضربه في π؟',
      [[p => 2 * p * d, 'ضربت القطر في ٢: المحيط = π × القطر، أو ٢ × π × نصف القطر.'], [p => p * d * d / 4, 'هذه المساحة لا المحيط.'], [p => p * d / 2, 'استعمل القطر كله أو ضاعف نصف القطر.']],
      { title: 'حافة البيدر', lab: `${N(d)} م`, diam: true, fill: 'rgba(202,165,92,.5)', lines: [`القطر = ${N(d)} م`, 'المحيط = ؟ م'] }, 'م'); }
  if (i === 2) { const d = R(8, 30);
    return round(`غطاء الطوي (البئر) دائري قطره ${N(d)} سم. ما مساحته؟`, p => p * (d / 2) ** 2, 'الصيغة تحتاج نصف القطر: ماذا تفعل بالقطر أولاً؟',
      [[p => p * d * d, 'عوّضت بالقطر في صيغة المساحة: اقسمه على ٢ أولاً.'], [p => p * d, 'هذا المحيط لا المساحة.']],
      { title: 'غطاء الطوي', lab: `${N(d)} سم`, diam: true, fill: 'rgba(139,107,71,.5)', lines: [`القطر = ${N(d)} سم`, 'المساحة = ؟ سم²'] }, 'سم²'); }
  if (i === 3) { const rr = R(3, 9);
    if (Math.random() < .5) return round(`حوض الزهور نصف دائرة نصف قطرها ${N(rr)} م. ما مساحته؟`, p => p * rr * rr / 2, 'نصف الدائرة نصف ماذا؟ احسب مساحة الدائرة كاملة أولاً.',
      [[p => p * rr * rr, 'هذه مساحة دائرة كاملة.'], [p => p * rr, 'هذا نصف محيط الدائرة.']], { title: 'حوض نصف دائري', lab: `${N(rr)} م`, half: true, fill: 'rgba(132,204,22,.45)', lines: [`نصف القطر = ${N(rr)} م`, 'المساحة = ؟ م²'] }, 'م²');
    return round(`حوض الزهور نصف دائرة نصف قطرها ${N(rr)} م، تحيطه منى بسياج. كم متراً طول السياج كله؟`, p => p * rr + 2 * rr, 'السياج يمشي على القوس ثم يعود على الحافة المستقيمة: ما طول كلٍّ منهما؟',
      [[p => p * rr, 'هذا القوس فقط: والحافة المستقيمة (القطر) جزء من المحيط.'], [p => 2 * p * rr, 'هذا محيط دائرة كاملة.'], [p => 2 * p * rr + 2 * rr, 'القوس نصف محيط الدائرة.']],
      { title: 'سياج نصف دائري', lab: `${N(rr)} م`, half: true, fill: 'rgba(132,204,22,.45)', lines: [`نصف القطر = ${N(rr)} م`, 'المحيط = ؟ م'] }, 'م'); }
  if (i === 4) { const C = R1(15, 80);
    return round(`حبل طوله ${N(C)} م يلتفّ حول الجابية مرة واحدة تماماً. ما قطرها؟`, p => C / p, 'المحيط = π × القطر: ما العملية العكسية التي تُبقي القطر وحده؟',
      [[p => C / (2 * p), 'هذا نصف القطر؛ المطلوب القطر.'], [p => C * p, 'القطر أصغر من المحيط: اقسم لا تضرب.']],
      { title: 'قطر الجابية', lab: 'ق = ؟', diam: true, lines: [`المحيط = ${N(C)} م`, 'القطر = ؟ م'] }, 'م'); }
  const A = R(20, 300);
  return round(`تريد منى جابية مساحة سطحها ${N(A)} م². كم يجب أن يكون نصف قطرها؟`, p => Math.sqrt(A / p), 'المساحة = π × نصف القطر²: اقسم على π، ثم ما العملية العكسية للتربيع؟',
    [[p => A / p, 'هذا مربع نصف القطر: بقي الجذر التربيعي.'], [p => Math.sqrt(A) / p, 'اقسم على π قبل الجذر.'], [p => 2 * Math.sqrt(A / p), 'هذا القطر.']],
    { title: 'جابية جديدة', lab: 'نق = ؟', lines: [`المساحة = ${N(A)} م²`, 'نصف القطر = ؟ م'] }, 'م');
}

function challenge() {
  const items = [], used = new Set(), fresh = f => { for (let k = 0; k < 60; k++) { const x = f(); const s = JSON.stringify(x); if (!used.has(s)) { used.add(s); return x; } } return f(); };
  const P = Math.PI, o = v => N(r1(v));
  { const r = fresh(() => R(3, 12)); items.push(choice(`مساحة دائرة نصف قطرها ${N(r)} سم (لأقرب منزلة عشرية):`, o(P * r * r) + ' سم²', [o(2 * P * r) + ' سم²', o(P * 4 * r * r) + ' سم²', o(P * r) + ' سم²'], 'المساحة = π × نصف القطر².', '8Ma3')); }
  { const d = fresh(() => { let x; do x = R(5, 25); while (x === 8); return x; });   /* ٨: المساحة تساوي ضعف المحيط فيتكرر خياران */ items.push(choice(`محيط دائرة قطرها ${N(d)} م (لأقرب منزلة عشرية):`, o(P * d) + ' م', [o(2 * P * d) + ' م', o(P * d * d / 4) + ' م', o(P * d / 2) + ' م'], 'المحيط = π × القطر.', '8Ma3')); }
  { const r = fresh(() => R(4, 10)); items.push(choice(`مساحة نصف دائرة نصف قطرها ${N(r)} سم (لأقرب منزلة عشرية):`, o(P * r * r / 2) + ' سم²', [o(P * r * r) + ' سم²', o(P * r) + ' سم²', o(P * r + 2 * r) + ' سم²'], 'نصف مساحة الدائرة كاملة.', '8Ma3')); }
  { const r = fresh(() => R(3, 9)), A = r1(P * r * r); items.push(choice(`دائرة مساحتها ${N(A)} سم². نصف قطرها تقريباً:`, N(r) + ' سم', [N(r * 2) + ' سم', o(A / P) + ' سم', o(Math.sqrt(A)) + ' سم'], 'اقسم على π ثم خذ الجذر التربيعي.', '8Ma3')); }
  items.push(choice('محيط نصف الدائرة يساوي نصف محيط الدائرة مضافاً إليه:', 'القطر', ['نصف القطر', 'π', 'المساحة'], 'الشكل له حافة مستقيمة أيضاً.', '8Ma3'));
  items.push(tf('إذا ضُرب نصف قطر دائرة في ٣ فإن مساحتها تُضرب في ٣.', false, 'جرّب: نصف القطر ١ ثم ٣. قارن المساحتين.', '8Ma3', 'تُضرب في ٩، لأن نصف القطر يُربَّع.'));
  items.push(tf('π هي نسبة محيط الدائرة إلى قطرها.', true, 'ما الذي يربط المحيط بالقطر؟', '8Ma3', 'المحيط = π × القطر.'));
  items.push(tf('زر π في الآلة الحاسبة يعطي جواباً أدق من استعمال ٣٫١٤.', true, 'هل ٣٫١٤ هي قيمة π تماماً؟', '8Ma3', 'π ≈ ٣٫١٤١٥٩٢٦٥…'));
  return items.sort(() => Math.random() - .5);
}

