function draw(g, w, h, t, S) {
  const r = S.r ? S.r.data : {}; farmBg(g, w, h, t);
  // حوض السقي: منشور مستطيل حجري فيه ماء يتموّج، وتغذّيه ساقية الفلج
  const bx = w * .2, by = h * .62, lv = S.done ? 1 : .55 + Math.sin(t * 1.4) * .03;
  g.fillStyle = '#3B82C4'; g.fillRect(0, by - 8, bx - 70, 12);
  prismFig(g, bx, by, [[-70, -50 * lv], [70, -50 * lv], [70, 0], [-70, 0]], 46, -30, { col: 'rgba(59,130,196,.55)', face: 'rgba(59,130,196,.75)' });
  prismFig(g, bx, by, [[-74, -64], [-70, -64], [-70, 0], [-74, 0]], 46, -30, { col: '#CBB892', face: '#B8A47C' });
  g.strokeStyle = '#8D7A57'; g.lineWidth = 4; g.strokeRect(bx - 74, by - 64, 148, 64);
  if (r.units) ladder(g, w * .4, h * .1, w * .56, r.units, r.facs, S.done ? r.facs.map((_, i) => i) : [], r.hl || []);
  (r.lines || []).forEach((l, k) => say(g, l, w * .68, h * .5 + k * 26, 17));
  if (S.done && r.ans) say(g, r.ans, w * .68, h * .5 + (r.lines || []).length * 26 + 8, 20, '#15803D');
  glow(g, w, h, S);
}

