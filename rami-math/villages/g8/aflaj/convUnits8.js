function challenge() {
  const items = [], used = new Set(), fresh = f => { for (let k = 0; k < 60; k++) { const x = f(); const s = JSON.stringify(x); if (!used.has(s)) { used.add(s); return x; } } return f(); };
  { const a = fresh(() => R(2, 9)); items.push(num(`حوّل ${N(a)} م² إلى سم².`, a * 10000, '١ م² = ١٠٠ × ١٠٠ سم².', '8Ma1')); }
  { const m = fresh(() => R(12, 98) * 10); items.push(num(`حوّل ${N(m)} ملم² إلى سم².`, m / 100, '١ سم² = ١٠٠ ملم².', '8Ma1')); }
  { const a = fresh(() => R(2, 9)); items.push(num(`حوّل ${N(a)} سم³ إلى ملم³.`, a * 1000, '١ سم³ = ١٠ × ١٠ × ١٠ ملم³.', '8Ma1')); }
  { const c = fresh(() => R(2, 9) * 1000); items.push(num(`حوّل ${N(c)} سم³ إلى لترات.`, c / 1000, '١ لتر = ١٠٠٠ مل = ١٠٠٠ سم³.', '8Ma1')); }
  { const h = fresh(() => R(2, 9)); items.push(num(`مزرعة مساحتها ${N(h)} هكتار. كم م² مساحتها؟`, h * 10000, '١ هكتار = ١٠٠٠٠ م².', '8Ma2')); }
  items.push(choice('كم سنتيمتراً مكعباً في المتر المكعب الواحد؟', '١٠٠٠٠٠٠', ['١٠٠', '١٠٠٠٠', '١٠٠٠'], 'مكعب ضلعه ١٠٠ سم: ١٠٠ × ١٠٠ × ١٠٠.', '8Ma1'));
  items.push(tf('١ سم³ = ١ مل.', true, 'تذكّر علاقة الحجم بالسعة.', '8Ma1', 'ولذلك ١ لتر = ١٠٠٠ سم³.'));
  items.push(tf('١ م² = ١٠٠ سم².', false, 'المتر المربع مربع ضلعه ١٠٠ سم.', '8Ma1', 'الصحيح ١ م² = ١٠٠٠٠ سم².'));
  items.push(match('صِل كل وحدة بما يساويها:', [['١ م²', '١٠٠٠٠ سم²'], ['١ سم²', '١٠٠ ملم²'], ['١ سم³', '١٠٠٠ ملم³'], ['١ لتر', '١٠٠٠ سم³']], 'كم بُعداً للمساحة؟ وكم للحجم؟', '8Ma1'));
  return items.sort(() => Math.random() - .5).slice(0, 8);
}

