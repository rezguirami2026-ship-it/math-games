function loadPick() {
  for (let t = 0; t < 60; t++) {
    const w = [R(11, 49) * 10, R(101, 499), R(101, 499), R(11, 49) * 10 + 5, R(101, 499)], [i, j] = shuf([0, 1, 2, 3, 4]).slice(0, 2), T = w[i] + w[j];
    if (new Set(w).size < 5) continue;
    let hits = 0; for (let m = 1; m < 32; m++) { let s = 0; for (let b = 0; b < 5; b++) if (m >> b & 1) s += w[b]; if (s === T) hits++; }
    if (hits === 1) return { w: w.map(v => v / 100), T: T / 100, ok: [w[i], w[j]].map(v => v / 100) };
  }
  return { w: [1.2, 2.35, 3.05, 0.75, 4.4], T: 3.1, ok: [2.35, 0.75] };
}
