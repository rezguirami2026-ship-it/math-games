const FORM = new Map(); NOUNS.forEach(n => [n.sing, n.plural, n.acc, n.acc.replace(/ً$/, 'ا')].forEach(f => FORM.set(f, n)));
const D = '٠١٢٣٤٥٦٧٨٩', val = s => +s.replace(/[٠-٩]/g, d => D.indexOf(d));
const words = [...FORM.keys()].sort((a, b) => b.length - a.length).map(w => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|');
// العدد (صحيح، ليس جزءاً من عشري أو وقت أو تاريخ)، بعلامة <b> اختيارية، ثم المعدود كلمة كاملة
const RE = new RegExp(`(^|[^٠-٩٫:/٬])(<b>)?([٠-٩]+)(</b>)?(\\s+)(${words})(?=$|[\\s،.؟!:؛)\\]<»])`, 'g');
const MATERIAL = /^\s+(عصير|ماء|طحين|سكر|حلوى|تمر|لبن|أرز|شاي|حليب|زيت|كعك)/;
const plain = s => s.replace(/<[^>]+>/g, '').trim();
export function fixCounts(text) {
  if (typeof text !== 'string' || !/[٠-٩]/.test(text)) return text;
  return text.replace(RE, (all, pre, b1, num, b2, sp, w, off, str) => {
    const after = str.slice(off + all.length);
    if (/[٫:]$/.test(str.slice(0, off + pre.length)) || /^[٫:][٠-٩]/.test(after)) return all;   // جزء من عشري أو وقت
    if (/^\s+من\s+(عشرة|مئة|ألف)/.test(after)) return all;   // ترميز القيمة المكانية (٣ أجزاء من عشرة) يبقى كما في الكتاب
    const n = val(num), f = FORM.get(w), wrap = s => (b1 ? '<b>' : '') + s + (b2 ? '</b>' : '');
    if (n === 0) return all;
    if (n === 1) return pre + wrap(MATERIAL.test(after) ? f.sing : f.one);   // «لكل كوب عصير» لا «كوب واحد عصير»
    if (n === 2) return pre + wrap(plain(str) === plain(all) ? f.dualN : f.dual);   // الإجابة القائمة وحدها بالرفع: «ريالان»
    const r = n % 100, noun = r >= 3 && r <= 10 ? f.plural : r >= 11 ? f.acc : f.sing;
    return pre + wrap(num) + sp + noun;
  }).replace(/(^|[^٠-٩٫])(<b>)?٢(<\/b>)?\s+أضعاف/g, (a, pre, b1, b2) => pre + (b1 ? '<b>' : '') + 'ضعف' + (b2 ? '</b>' : ''))   // «٢ أضعاف ٤» ← «ضعف ٤»
    .replace(/بـ\s+(<b>)?(?=[ء-ي])/g, 'ب$1');   // «بـ ريال واحد» ← «بريال واحد»
}
const FIELDS = ['q', 'hint', 'why', 'tail'], LISTS = ['opts', 'left', 'right', 'bins', 'steps'];
/* يصحّح سؤالاً مرة واحدة (آمن للتكرار) */
export function fixItem(it) {
  if (!it || it._ar) return it;
  FIELDS.forEach(k => { if (typeof it[k] === 'string') it[k] = fixCounts(it[k]); });
  LISTS.forEach(k => { if (Array.isArray(it[k])) it[k] = it[k].map(fixCounts); });
  if (Array.isArray(it.cards)) it.cards.forEach(c => { if (c && typeof c.t === 'string') c.t = fixCounts(c.t); });
  it._ar = 1; return it;
}
